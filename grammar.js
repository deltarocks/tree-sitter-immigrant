export default grammar({
	name: 'immigrant',
	fileTypes: ['schema'],
	scope: 'immigrant',
	rules: {
		source_file: $ => choice($.test_schema, $.normal_schema),

		test_schema: $ => seq(
			optional(field('setup', seq(
				'!!!SETUP',
				$.test_explaination,
				$.normal_schema,
			))),
			'!!!TEST',
			$.test_explaination,
			field('first_example', $.normal_schema),
			optional(field('examples', seq(
				'!!!UPDATE',
				$.test_explaination,
				$.normal_schema,
			))),
			optional(field('result', $.sql_block)),
		),
		sql_block: $ => seq('!!!RESULT', repeat(/.+/)),

		test_explaination: $ => /[^\n]*\n/,

		normal_schema: $ => seq(
			optional($.version_directive),
			repeat1($.declaration),
		),
		version_directive: $ => seq('@!schema_version', $.number, ';'),
		declaration: $ => choice(
			$.scalar_declaration,
			$.table_declaration,
			$.view_declaration,
			$.enum_declaration,
			$.composite_declaration,
			$.mixin_declaration,
			$.role_declaration,
			$.extension_declaration,
		),
		scalar_declaration: $ => seq(
			repeat($.attribute),
			'scalar',
			field('name', $.type_identifier),
			optional(field('db_name', $.string)),
			'=',
			$.decl,
			optional($.field_annotation),
			';',
		),
		table_declaration: $ => seq(
			repeat($.attribute),
			'table',
			field('name', $.type_identifier),
			optional(field('db_name', $.string)),
			'{',
			repeat(choice($.table_field, $.mixin_inclusion)),
			repeat($.table_annotation),
			'}',
			';',
		),
		role_declaration: $ => seq(
			repeat($.attribute),
			'role',
			field('name', $.role_identifier),
			optional(field('db_name', $.string)),
			'{',
			repeat($.role_annotation),
			'}',
			';',
		),
		role_annotation: $ => seq(choice(
			$.default_permissions,
			'@external',
		), ';'),
		default_permissions: $ => seq(
			'default',
			'{',
			repeat(seq($.permission, ';')),
			'}',
		),
		extension_declaration: $ => seq(
			repeat($.attribute),
			'extension',
			field('name', $.extension_identifier),
			optional(field('db_name', $.string)),
			optional(seq(
				'{',
				repeat($.extension_annotation),
				'}',
			)),
			';',
		),
		extension_annotation: $ => seq(choice(
			seq('version', $.string),
			'cascade',
			'@external',
		), ';'),
		permission: $ => choice('select', 'insert', 'update', 'delete'),
		role_grant: $ => seq(
			'@role',
			field('role', $.role_identifier),
			'{',
			repeat(seq($.permission, ';')),
			'}',
		),
		policy_annotation: $ => seq(
			'@policy',
			'.',
			'for',
			'(',
			field('role', $.role_identifier),
			')',
			optional(field('db_name', $.string)),
			'(',
			$.expression,
			')',
		),
		mixin_declaration: $ => seq(
			repeat($.attribute),
			'@mixin',
			field('name', $.type_identifier),
			'{',
			repeat(choice($.table_field, $.mixin_inclusion)),
			repeat($.table_annotation),
			'}',
			';',
		),
		mixin_inclusion: $ => seq(
			'@mixin',
			$.type_identifier,
			';',
		),
		decl: $ => choice(
			seq('sql"""', optional($.decl_body_multiline), '"""'),
			seq('sql"', optional($.decl_body_single), '"'),
		),
		decl_body_multiline: $ => repeat1(choice($.decl_column, $.decl_table, $.decl_raw_multiline)),
		decl_body_single: $ => repeat1(choice($.decl_column, $.decl_table, $.decl_raw_single)),
		decl_raw_single: $ => prec.right(repeat1(
			/[^"{}]+/,
		)),
		decl_raw_multiline: $ => prec.right(repeat1(
			// FIXME: negative lookahead for """ should be here
			/[^"{}]+/,
		)),
		decl_column: $ => seq(
			'{',
			field('table', $.type_identifier),
			'.',
			field('column', $.field_identifier),
			'}',
		),
		decl_table: $ => seq(
			'{',
			field('table', $.type_identifier),
			'}',
		),
		view_declaration: $ => seq(
			repeat($.attribute),
			'view',
			optional(seq(
				'.',
				'materialized',
			)),
			field('name', $.type_identifier),
			optional(field('db_name', $.string)),
			optional(seq(
				'{',
				repeat($.view_annotation),
				'}',
			)),
			'=',
			$.decl,
			';',
		),
		view_annotation: $ => seq(choice(
			'@security_definer',
			$.role_grant,
		), ';'),
		enum_declaration: $ => seq(
			repeat($.attribute),
			'enum',
			field('name', $.type_identifier),
			optional(field('db_name', $.string)),
			'{',
			repeat($.enum_field),
			'}',
			';',
		),
		composite_declaration: $ => seq(
			repeat($.attribute),
			'struct',
			field('name', $.type_identifier),
			optional(field('db_name', $.string)),
			'{',
			repeat(choice($.composite_field, $.composite_annotation)),
			'}',
			';',
		),
		composite_annotation: $ => seq($.expr_annotation, ';'),

		enum_field: $ => seq(
			field('name', $.variant_identifier),
			optional(field('db_name', $.string)),
			';'
		),
		composite_field: $ => seq(
			field('name', $.field_identifier),
				':',
				choice($.decl, $.type_identifier),
			optional($.field_annotation),
			';'
		),
		table_field: $ => seq(
			repeat($.attribute),
			field('name', $.field_identifier),
			optional($.string),
			optional(field('type', seq(
				':',
				choice($.decl, $.type_identifier),
			))),
			optional('?'),
			optional($.field_annotation),
			';',
		),

		type_identifier: $ => $.identifier,
		field_identifier: $ => $.identifier,
		variant_identifier: $ => $.identifier,
		role_identifier: $ => $.identifier,
		extension_identifier: $ => $.identifier,
		function_identifier: $ => $.identifier,
		annotation_identifier: $ => $.identifier,
		attribute_identifier: $ => $.identifier,
		attribute_field_identifier: $ => $.identifier,
		identifier: $ => /[a-zA-Z_][a-zA-Z0-9_]*/,
		string: $ => seq(
			'"',
			repeat(choice(
				$.string_escape,
				/[^"]/,
			)),
			'"'
		),
		string_escape: $ => '\\"',
		number: $ => /[0-9]+/,


		attribute: $ => seq(
			'#',
			$.attribute_identifier,
			optional(seq(
				'(',
				repeat1($.attribute_field),
				')',
			)),
		),
		attribute_field: $ => seq(
			$.attribute_field_identifier,
			optional(seq(
				'=',
				$.string,
			)),
			optional(','),
		),

		field_annotation: $ => repeat1(choice(
			'@external',
			$.expr_annotation,
			$.policy_annotation,
			$.fk_annotation,
			seq($.pk_annotation, optional($.field_list)),
		)),
		table_annotation: $ => seq(choice(
			$.expr_annotation,
			$.policy_annotation,
			$.role_grant,
			'@external',
			'@rls.owner',
			'@rls',
			seq(optional($.field_list), $.fk_annotation),
			seq($.pk_annotation, $.field_list),
		), ';'),
		fk_annotation: $ => seq(
			'~',
			optional(seq(
				'.',
				$.on_update,
			)),
			$.type_identifier,
			optional($.field_list),
		),
		on_update: $ => choice('set_null', 'set_default', 'restrict', 'noop', 'cascade'),
		expr_annotation: $ => seq(
			choice('@default', seq('@check', optional($.string)), '@initialize_as'),
			'(',
			$.expression,
			')',
		),
		pk_annotation: $ => choice(
			seq('@primary_key', optional(field('db_name', $.string))),
			seq('@unique', optional(field('db_name', $.string))),
			seq('@index', repeat(seq(
				'.',
				$.index_attr,
			)), optional(field('db_name', $.string))),
			'@inline',
		),
		index_attr: $ => choice(
			'unique',
			seq('opclass', '(', $.type_identifier, ')'),
			seq('using', '(', $.type_identifier, ')'),
			seq('with', '(', $.string, ')'),
		),
		field_list: $ => seq(
			'(',
			optional(seq(
				$.field_identifier,
				repeat(seq(',', $.field_identifier)),
				optional(','),
			)),
			')',
		),
		expression: $ => choice(
			$.function_call,
			$.binary_expression,
			$.unary_expression,
			$.if_expression,
			$.parened_expression,
			$.placeholder,
			$.null_literal,
			$.boolean_literal,
			$.field_identifier,
			$.string,
			$.number,
		),
		placeholder: $ => '_',
		null_literal: $ => 'null',
		boolean_literal: $ => choice('true', 'false'),
		if_expression: $ => prec.right(seq(
			'if', $.expression, 'then', $.expression, 'else', $.expression,
		)),
		function_call: $ => prec.left(10, seq(
			$.function_identifier,
			'(',
			optional(seq(
				repeat(seq($.expression, ',')),
				$.expression, optional(','),
			)),
			')',
		)),
		unary_expression: $ => prec(7, seq(choice('!', '-', '+'), $.expression)),
		binary_expression: $ => choice(
			prec.left(1, seq($.expression, '||', $.expression)),
			prec.left(2, seq($.expression, '&&', $.expression)),
			prec.left(3, seq($.expression, choice('==', '!=', '~~', "===", "!=="), $.expression)),
			prec.left(4, seq($.expression, choice('<', '>', '<=', '>='), $.expression)),
			prec.left(5, seq($.expression, '+', $.expression)),
			prec.left(5, seq($.expression, '-', $.expression)),
			prec.left(6, seq($.expression, '*', $.expression)),
			prec.left(6, seq($.expression, '/', $.expression)),
			prec.left(6, seq($.expression, '%', $.expression)),
			prec.left(8, seq($.expression, '::', $.type_identifier)),
			prec.left(8, seq($.expression, '.', $.field_identifier)),
		),
		parened_expression: $ => seq(
			'(',
			$.expression,
			')',
		),
		comment: $ =>
			/\/\/[^\n]*/,
	},
	conflicts: $ => [
		[$.function_call, $.expression],
	],
	extras: $=>[$.comment, /[ \t\n]+/],
});
